function _precompile_workload()
    for text in EXPRESSIONS
        try
            value = Core.eval(@__MODULE__, Meta.parse(text))
            encode_value(value)
        catch exception
            exception isa InterruptException && rethrow()
        end
    end
    for value in (1.0, 2.0 + 1.0im, "text", eq_vec(1, 2, 3), eq_matrix(2, 2, 1, 2, 3, 4),
                  eq_mul(3.0, eq_unit("m")), eq_pow(eq_mul(3.0, eq_unit("m")), 2.0),
                  eq_matrix(20, 20, (1.0:400.0)...))
        encode_value(value)
    end
    return nothing
end

if ccall(:jl_generating_output, Cint, ()) == 1
    try
        _precompile_workload()
    catch exception
        @warn "EqRuntime precompile workload failed" exception
    end
end
